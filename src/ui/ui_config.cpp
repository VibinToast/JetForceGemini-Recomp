// Every UI frame (ui_state.cpp): while a split pack (.rtz.001, ...) is being joined, shows the progress on the Textures
// page; when it is joined, the list is made again to show it. (Parts are looked for at start-up and by Reload Pack.)
void jfg_config_pack_join_tick() {
    using clock = std::chrono::steady_clock;
    static clock::time_point next_look{};
    static int finished_seen = 0;
    const clock::time_point now = clock::now();
    if (now < next_look) return;
    next_look = now + std::chrono::milliseconds(500);
    int finished = 0;
    const std::string text = jfg::settings::texture_pack_join_text(finished);
    if (text != jfg_pack_join_text) {
        jfg_pack_join_text = text;
        if (jfg_textures_model_handle) jfg_textures_model_handle.DirtyVariable("pack_join_text");
    }
    // The official HD pack's latest version (asked once, with Check for Updates and the option on): when it arrives or
    // an install ends, the cards are made again for their "Update available" tag.
    jfg_official_check_start();
    static int official_seen = -1;
    const int official = jfg_official_state(false).serial;
    if (finished != finished_seen || official != official_seen) {
        finished_seen = finished;
        official_seen = official;
        jfg_config_menu_refresh();
    }
}

// Opening a website (the launcher's links, a texture pack's website) asks first: it takes you out of the game into the
// web browser, which on a handheld PC is easy to do by accident. return_id: what gets the focus back after the prompt.
void jfg_open_url_prompt(const std::string& url, const std::string& return_id) {
    if (url.rfind("https://", 0) != 0 && url.rfind("http://", 0) != 0) return;
    std::string shown = url.substr(url.find("//") + 2);
    if (!shown.empty() && shown.back() == '/') shown.pop_back();
    recompui::open_choice_prompt(
        "Open the website?",
        shown + " opens in your web browser, outside the game.",
        "Open",
        "Cancel",
        [url]() { SDL_OpenURL(url.c_str()); },
        []() {},
        recompui::ButtonVariant::Primary,
        recompui::ButtonVariant::Tertiary,
        true,
        return_id);
}

