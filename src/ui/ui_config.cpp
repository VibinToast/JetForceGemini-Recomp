// A texture pack in the Textures tab's list: its credits.json details (if any) and its image (pack_image.png), loaded into
// the UI as "jfg_pack_<n>" (image is its source in RML, "/jfg_pack_<n>", as for the launcher's logo; empty if none).
struct JfgPackEntry {
    Rml::String folder; Rml::String label; bool selected = false;
    Rml::String version, author; // "Version 1.2", "by VibinToast" (empty if credits.json has none)
    Rml::String website, description, image;
    bool no_details = false; // a pack without credits.json
    Rml::String kind;        // the label on its button: "Folder" or ".rtz" ("" for Off)
    Rml::String variant;     // credits.json's variant ("4K"), shown as a bubble after the name (without "-4K")
    Rml::String size;        // "3.0 GB": the .rtz, or every file in the folder
    bool update = false;     // the official HD pack, with a newer version out: "Update available"
};
static std::vector<JfgProfileEntry> jfg_profile_entries;
static std::vector<JfgPackEntry> jfg_pack_entries;
static Rml::String jfg_new_profile_name;
static Rml::String jfg_pack_status, jfg_dump_status;
static Rml::String jfg_pack_status_variant, jfg_pack_status_count; // the "In use" line: name, variant bubble, " (n textures)"
static Rml::String jfg_pack_join_text; // joining a split pack: progress or result (jfg_config_pack_join_tick)
static int jfg_pack_view = 0; // the pack whose details the Textures tab shows (the focused one, at first the one in use)
// The packs' images given to the UI: folder -> (details serial, image src).
static std::map<std::string, std::pair<int, std::string>> jfg_pack_images;
static int jfg_pack_image_count = 0;

static void jfg_fill_pack_entry(JfgPackEntry& e) {
    if (e.folder.empty()) {
        e.description = "The game's own textures.";
        return;
    }
    std::string ext = e.folder.size() > 4 ? e.folder.substr(e.folder.size() - 4) : std::string();
    for (char& ch : ext) ch = (char)std::tolower((unsigned char)ch);
    e.kind = ext == ".rtz" ? ".rtz" : "Folder";
    {
        std::error_code ec;
        const std::filesystem::path path = std::filesystem::u8path(e.folder);
        uintmax_t bytes = 0;
        if (ext == ".rtz") bytes = std::filesystem::file_size(path, ec);
        else {
            for (std::filesystem::recursive_directory_iterator it(path, ec), end; !ec && it != end; it.increment(ec)) {
                std::error_code e2;
                if (it->is_regular_file(e2)) bytes += it->file_size(e2);
            }
        }
        char text[32] = {};
        if (bytes >= (1ull << 30)) std::snprintf(text, sizeof(text), "%.1f GB", bytes / 1073741824.0);
        else if (bytes > 0) std::snprintf(text, sizeof(text), "%.0f MB", std::max(1.0, bytes / 1048576.0));
        e.size = text;
    }
    e.update = jfg_official_outdated(e.folder);
    jfg::settings::TexturePackDetails d = jfg::settings::texture_pack_details(e.folder);
    if (!d.version.empty()) e.version = "Version " + d.version;
    if (!d.author.empty()) e.author = (e.version.empty() ? "By " : "by ") + d.author;
    e.website = d.website;
    e.description = d.has_json ? d.description : std::string();
    e.no_details = !d.has_json;
    // Official_Recomp_HD-4K: the name, then 4K in a bubble.
    if (!d.variant.empty()) {
        e.variant = d.variant;
        const std::string suffix = "-" + d.variant;
        if (e.label.size() > suffix.size() && e.label.compare(e.label.size() - suffix.size(), suffix.size(), suffix) == 0) {
            e.label.resize(e.label.size() - suffix.size());
        }
    }
    // The images wait for the next refresh while the UI is still being made (none can be queued yet).
    if (!recompui::can_queue_images()) return;
    auto it = jfg_pack_images.find(e.folder);
    if (it != jfg_pack_images.end() && it->second.first != d.serial) {
        recompui::release_image(it->second.second);
        jfg_pack_images.erase(it);
        it = jfg_pack_images.end();
    }
    if (it == jfg_pack_images.end() && !d.image.empty()) {
        const std::string src = "jfg_pack_" + std::to_string(++jfg_pack_image_count);
        recompui::queue_image_from_bytes_file(src, d.image);
        it = jfg_pack_images.emplace(e.folder, std::make_pair(d.serial, src)).first;
    }
    if (it != jfg_pack_images.end()) e.image = "/" + it->second.second;
}

// Rebuilds the lists and marks every port value as changed (settings can also change from the F9 menu and profiles).
void jfg_config_menu_refresh() {
    jfg_profile_entries.clear();
    const std::string active = jfg::settings::active_profile();
    for (const std::string& n : jfg::settings::profiles()) jfg_profile_entries.push_back({ n, n == active });
    jfg_pack_entries.clear();
    const std::string pack = jfg::settings::texture_pack();
    for (const std::string& f : jfg::settings::texture_packs()) {
        JfgPackEntry& e = jfg_pack_entries.emplace_back();
        e.folder = f;
        e.label = jfg::settings::texture_pack_name(f);
        e.selected = f == pack;
        jfg_fill_pack_entry(e);
        if (e.selected) jfg_pack_view = (int)jfg_pack_entries.size() - 1;
    }
    if (jfg_pack_view >= (int)jfg_pack_entries.size()) jfg_pack_view = 0;
    const int count = jfg::settings::texture_pack_count();
    // "In use: <name> [4K] (n textures)": the name and bubble as on its card.
    jfg_pack_status = "In use: " + jfg::settings::texture_pack_name(pack);
    jfg_pack_status_variant.clear();
    for (const JfgPackEntry& e : jfg_pack_entries) {
        if (e.selected) { jfg_pack_status = "In use: " + e.label; jfg_pack_status_variant = e.variant; }
    }
    jfg_pack_status_count = pack.empty() || count < 0 ? std::string() : " (" + std::to_string(count) + " textures)";
    const int dumped = jfg::settings::dumped_texture_files();
    jfg_dump_status = dumped >= 0 ? "texture_dump folder: " + std::to_string(dumped) + " files." : std::string();
    for (Rml::DataModelHandle* handle : { &jfg_general_model_handle, &jfg_gameplay_model_handle, &jfg_controls_model_handle,
                                          &jfg_graphics_model_handle, &jfg_textures_model_handle }) {
        if (*handle) handle->DirtyAllVariables();
    }
    if (jfg_profiles_model_handle) jfg_profiles_model_handle.DirtyAllVariables();
    if (controls_model_handle) controls_model_handle.DirtyVariable("jfg_bindings_unused");
}

// True if controller config menu is open, false if keyboard config menu is open, undefined otherwise
bool configuring_controller = false;

int recompui::config_tab_to_index(recompui::ConfigTab tab) {
    switch (tab) {
    // JFG PORT: the tabs are Profiles, General, Gameplay, Controls, Bindings, Graphics, Textures and Mods
    // (assets/config_menu.rml). The recomp's General options (stick, rumble) are on the port's Controls tab, its Sound
    // option on General, its Controls tab is Bindings and its Graphics options are on the port's Graphics tab.
    case recompui::ConfigTab::General:
    case recompui::ConfigTab::Sound:
        return 1;
    case recompui::ConfigTab::Controls:
        return 4;
    case recompui::ConfigTab::Graphics:
        return 5;
    case recompui::ConfigTab::Mods:
        return 7;
    default:
        assert(false && "Unknown config tab.");
        return 0;
    }
}

template <typename T>
void get_option(const T& input, Rml::Variant& output) {
    std::string value = "";
    to_json(value, input);

    if (value.empty()) {
        throw std::runtime_error("Invalid value :" + std::to_string(int(input)));
    }

    output = value;
}

template <typename T>
void set_option(T& output, const Rml::Variant& input) {
    T value = T::OptionCount;
    from_json(input.Get<std::string>(), value);

    if (value == T::OptionCount) {
        throw std::runtime_error("Invalid value :" + input.Get<std::string>());
    }

    output = value;
}

template <typename T>
void bind_option(Rml::DataModelConstructor& constructor, const std::string& name, T* option) {
    constructor.BindFunc(name,
        [option](Rml::Variant& out) { get_option(*option, out); },
        [option](const Rml::Variant& in) {
            set_option(*option, in);
            graphics_model_handle.DirtyVariable("options_changed");
            graphics_model_handle.DirtyVariable("ds_info");
        }
    );
};

template <typename T>
void bind_atomic(Rml::DataModelConstructor& constructor, Rml::DataModelHandle handle, const char* name, std::atomic<T>* atomic_val) {
    constructor.BindFunc(name,
        [atomic_val](Rml::Variant& out) {
            out = atomic_val->load();
        },
        [atomic_val, handle, name](const Rml::Variant& in) mutable {
            atomic_val->store(in.Get<T>());
            handle.DirtyVariable(name);
        }
    );
}

