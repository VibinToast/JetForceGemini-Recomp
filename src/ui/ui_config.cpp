    // JFG PORT: one binding per option key, read and written through jfg::settings (or upstream_options).
    template <size_t N>
    void bind_jfg_keys(Rml::DataModelConstructor& constructor, const char* const (&keys)[N]) {
        for (const char* key : keys) {
            const std::string k = key;
            const UpstreamOption* upstream = nullptr;
            for (const UpstreamOption& o : upstream_options) if (k == o.key) upstream = &o;
            if (upstream != nullptr) {
                constructor.BindFunc(k,
                    [upstream](Rml::Variant& out) { out = upstream->get(); },
                    [upstream](const Rml::Variant& in) { upstream->set(in.Get<int>()); jfg_config_menu_refresh(); });
                continue;
            }
            constructor.BindFunc(k,
                [k](Rml::Variant& out) { out = jfg::settings::get(k); },
                [k](const Rml::Variant& in) { jfg::settings::set(k, in.Get<int>()); jfg_config_menu_refresh(); });
        }
    }

    template <size_t N>
    Rml::DataModelHandle make_jfg_options_model(Rml::Context* context, const char* name, const char* const (&keys)[N]) {
        Rml::DataModelConstructor constructor = context->CreateDataModel(name);
        if (!constructor) throw std::runtime_error(std::string("Failed to make RmlUi data model ") + name);
        bind_config_list_events(constructor);
        bind_jfg_keys(constructor, keys);
        return constructor.GetModelHandle();
    }

    void make_jfg_bindings(Rml::Context* context) {
        jfg_general_model_handle = make_jfg_options_model(context, "jfg_general_model", jfg_general_keys);
        jfg_gameplay_model_handle = make_jfg_options_model(context, "jfg_gameplay_model", jfg_gameplay_keys);
        jfg_controls_model_handle = make_jfg_options_model(context, "jfg_controls_model", jfg_controls_keys);
        jfg_graphics_model_handle = make_jfg_options_model(context, "jfg_graphics_model", jfg_graphics_keys);
        {
            Rml::DataModelConstructor constructor = context->CreateDataModel("jfg_textures_model");
            if (!constructor) throw std::runtime_error("Failed to make RmlUi data model for the Textures tab");
            bind_config_list_events(constructor);
            bind_jfg_keys(constructor, jfg_textures_keys);
            if (auto entry = constructor.RegisterStruct<JfgPackEntry>()) {
                entry.RegisterMember("folder", &JfgPackEntry::folder);
                entry.RegisterMember("label", &JfgPackEntry::label);
                entry.RegisterMember("selected", &JfgPackEntry::selected);
                entry.RegisterMember("version", &JfgPackEntry::version);
                entry.RegisterMember("author", &JfgPackEntry::author);
                entry.RegisterMember("website", &JfgPackEntry::website);
                entry.RegisterMember("description", &JfgPackEntry::description);
                entry.RegisterMember("image", &JfgPackEntry::image);
                entry.RegisterMember("no_details", &JfgPackEntry::no_details);
                entry.RegisterMember("kind", &JfgPackEntry::kind);
                entry.RegisterMember("variant", &JfgPackEntry::variant);
                entry.RegisterMember("size", &JfgPackEntry::size);
                entry.RegisterMember("update", &JfgPackEntry::update);
            }
            constructor.RegisterArray<std::vector<JfgPackEntry>>();
            constructor.Bind("packs", &jfg_pack_entries);
            constructor.Bind("pack_status", &jfg_pack_status);
            constructor.Bind("pack_status_variant", &jfg_pack_status_variant);
            constructor.Bind("pack_status_count", &jfg_pack_status_count);
            constructor.Bind("dump_status", &jfg_dump_status);
            constructor.Bind("pack_join_text", &jfg_pack_join_text);
            constructor.Bind("pack_view", &jfg_pack_view);
            // A pack button got focus or the mouse: its details on the right (they stay while the focus moves on to
            // the website button).
            constructor.BindEventCallback("view_pack", [](Rml::DataModelHandle model, Rml::Event&, const Rml::VariantList& args) {
                if (args.empty()) return;
                jfg_pack_view = args[0].Get<int>();
                focused_config_option_index = -1; // not a dumping option's description
                model.DirtyVariable("pack_view");
                model.DirtyVariable("cur_config_index");
            });
            constructor.BindEventCallback("open_pack_website", [](Rml::DataModelHandle, Rml::Event& event, const Rml::VariantList&) {
                if (jfg_pack_view < 0 || jfg_pack_view >= (int)jfg_pack_entries.size()) return;
                Rml::Element* button = event.GetCurrentElement();
                jfg_open_url_prompt(jfg_pack_entries[jfg_pack_view].website, button != nullptr ? button->GetId() : std::string());
            });
            constructor.BindEventCallback("set_pack", [](Rml::DataModelHandle, Rml::Event&, const Rml::VariantList& args) {
                jfg::settings::set_texture_pack(args.empty() ? std::string() : args[0].Get<Rml::String>());
                jfg_config_menu_refresh();
            });
            constructor.BindEventCallback("reload_pack", [](Rml::DataModelHandle, Rml::Event&, const Rml::VariantList&) {
                jfg::settings::texture_pack_join_poll(); // split packs put in texture_packs since the start
                jfg::settings::set_texture_pack(jfg::settings::texture_pack());
                jfg_config_menu_refresh();
            });
            constructor.BindEventCallback("open_pack_folder", [](Rml::DataModelHandle, Rml::Event&, const Rml::VariantList&) {
                jfg::settings::open_texture_packs_folder();
            });
            jfg_textures_model_handle = constructor.GetModelHandle();
        }
        {
            Rml::DataModelConstructor constructor = context->CreateDataModel("jfg_profiles_model");
            if (!constructor) throw std::runtime_error("Failed to make RmlUi data model for the Profiles tab");
            if (auto entry = constructor.RegisterStruct<JfgProfileEntry>()) {
                entry.RegisterMember("name", &JfgProfileEntry::name);
                entry.RegisterMember("selected", &JfgProfileEntry::selected);
            }
            constructor.RegisterArray<std::vector<JfgProfileEntry>>();
            constructor.Bind("profiles", &jfg_profile_entries);
            constructor.Bind("new_profile_name", &jfg_new_profile_name);
            constructor.BindFunc("active_profile", [](Rml::Variant& out) {
                const std::string a = jfg::settings::active_profile();
                out = a.empty() ? Rml::String("(none - your own settings)") : a;
            });
            constructor.BindFunc("profile_description", [](Rml::Variant& out) { out = jfg::settings::profile_description(); });
            constructor.BindFunc("profile_changed", [](Rml::Variant& out) { out = jfg::settings::profile_changed(); });
            constructor.BindFunc("profile_deletable", [](Rml::Variant& out) {
                out = !jfg::settings::active_profile().empty() && !jfg::settings::active_profile_is_builtin();
            });
            constructor.BindFunc("profile_message", [](Rml::Variant& out) { out = jfg::settings::profile_message(); });
            constructor.BindFunc("keep_controls",
                [](Rml::Variant& out) { out = jfg::settings::keep_controls() ? 1 : 0; },
                [](const Rml::Variant& in) { jfg::settings::set_keep_controls(in.Get<int>() != 0); jfg_config_menu_refresh(); });
            // What the profile changes is shown first (issue #7); it is applied on Apply.
            constructor.BindEventCallback("choose_profile", [](Rml::DataModelHandle, Rml::Event&, const Rml::VariantList& args) {
                if (args.empty()) return;
                const std::string name = args[0].Get<Rml::String>();
                if (name.empty() || name[0] == '(') return;
                const std::string changes = jfg::settings::profile_preview(name);
                if (changes.empty()) {
                    jfg::settings::choose_profile(name);
                    jfg_config_menu_refresh();
                    return;
                }
                recompui::open_choice_prompt("Apply the \"" + name + "\" profile?", changes, "Apply", "Cancel",
                    [name]() { jfg::settings::choose_profile(name); jfg_config_menu_refresh(); },
                    []() {},
                    recompui::ButtonVariant::Success, recompui::ButtonVariant::Tertiary, false);
            });
            constructor.BindEventCallback("save_profile", [](Rml::DataModelHandle, Rml::Event&, const Rml::VariantList&) {
                if (jfg::settings::save_profile(jfg_new_profile_name)) jfg_new_profile_name.clear();
                jfg_config_menu_refresh();
            });
            constructor.BindEventCallback("delete_profile", [](Rml::DataModelHandle, Rml::Event&, const Rml::VariantList&) {
                jfg::settings::delete_active_profile();
                jfg_config_menu_refresh();
            });
            jfg_profiles_model_handle = constructor.GetModelHandle();
        }
        jfg_config_menu_refresh();
    }

