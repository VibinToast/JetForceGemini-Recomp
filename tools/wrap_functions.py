#!/usr/bin/env python3
"""Post-process N64Recomp output: put the port's wrappers around game functions (tools/wrapped_funcs.txt).

The port never changes a game function itself. For each listed function <name>:
  - the recompiled function is renamed <name>_orig: the game's code, unchanged;
  - a new <name> (RecompiledFuncs/jfg_wrapped.c) calls the port's wrapper, jfg_wrap_<name> (src/jfg/, declared with
    JFG_WRAP in jfg_hooks.h), which runs the port's code and calls <name>_orig.
Every caller reaches <name>: direct calls in the generated code, the runtime's function table (function pointers,
JFG_DYN_CALL) and mods calling into the game. jfg_register_wrapped() tells the runtime (register_base_wrapper) that
mods' patches and hooks apply to <name>_orig, so the wrapper keeps running around them.

Run last, after fix_dynamic_relocs.py and refuse_mod_hooks.py (they find functions by their original names).

Usage: wrap_functions.py <RecompiledFuncs dir> <wrapped_funcs.txt>
"""
import glob, os, re, sys

PROTO = "(uint8_t* rdram, recomp_context* ctx)"


def main():
    out_dir, list_path = sys.argv[1], sys.argv[2]
    names = [l.split("#")[0].strip() for l in open(list_path, encoding="utf-8")]
    names = [n for n in names if n]
    if len(set(names)) != len(names):
        sys.exit("wrap_functions: a name is listed twice in " + list_path)

    sources = {p: open(p, encoding="utf-8").read() for p in glob.glob(os.path.join(out_dir, "funcs_*.c"))}
    for name in names:
        define = "RECOMP_FUNC void %s%s {" % (name, PROTO)
        hits = [p for p, text in sources.items() if define in text]
        if len(hits) != 1:
            sys.exit("wrap_functions: %s is defined %d times in the generated code" % (name, len(hits)))
        sources[hits[0]] = sources[hits[0]].replace(define, "RECOMP_FUNC void %s_orig%s {" % (name, PROTO))
    for path, text in sources.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)

    header = os.path.join(out_dir, "funcs.h")
    text = open(header, encoding="utf-8").read()
    for name in names:
        decl = "void %s%s;" % (name, PROTO)
        if decl not in text:
            sys.exit("wrap_functions: %s is not declared in funcs.h" % name)
        text = text.replace(decl, decl + "\nvoid %s_orig%s;" % (name, PROTO))
    with open(header, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    lines = ["// Generated by tools/wrap_functions.py from tools/wrapped_funcs.txt. Each game function listed there now runs",
             "// the port's wrapper (jfg_wrap_<name>, src/jfg/), which calls <name>_orig, the recompiled original.",
             '#include "funcs.h"', ""]
    for name in names:
        lines.append("void jfg_wrap_%s%s;" % (name, PROTO))
        lines.append("RECOMP_FUNC void %s%s { jfg_wrap_%s(rdram, ctx); }" % (name, PROTO, name))
    lines += ["", "// Called by the port (jfg_mods.cpp) with recomp::overlays::register_base_wrapper.",
              "void jfg_register_wrapped(void (*reg)(recomp_func_t* wrapped, recomp_func_t* original)) {"]
    lines += ["    reg(%s, %s_orig);" % (name, name) for name in names]
    lines.append("}")
    with open(os.path.join(out_dir, "jfg_wrapped.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrap_functions: %d game functions wrapped by the port" % len(names))


if __name__ == "__main__":
    main()
