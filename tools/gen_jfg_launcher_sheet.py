#!/usr/bin/env python3
"""Builds the launcher's animated VibinToast icon (About page) from a video of it:
    python3 tools/gen_jfg_launcher_sheet.py <VibinToast-icon.webm>
Writes assets/jfg_launcher/vibintoast.png (every 2nd frame, 160x160, 18 per row) and assets/jfg_launcher/vibintoast.rcss
(one sprite per frame: toast0, toast1, ...). src/ui/ui_launcher.cpp steps through the sprites at 30 per second
(TOAST_FRAMES / TOAST_FPS there must match). Needs ffmpeg (with libvpx for a transparent .webm) and Pillow."""
import glob, os, subprocess, sys, tempfile
from PIL import Image

FRAME = 160      # sprite size in pixels
STEP = 2         # keep every 2nd frame of the 60 fps video (30 fps)
COLUMNS = 18

def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "assets", "jfg_launcher")
    with tempfile.TemporaryDirectory() as tmp:
        # libvpx-vp9 keeps the video's alpha channel (the default decoder drops it).
        subprocess.run(["ffmpeg", "-v", "error", "-c:v", "libvpx-vp9", "-i", sys.argv[1], os.path.join(tmp, "f_%04d.png")], check=True)
        frames = sorted(glob.glob(os.path.join(tmp, "f_*.png")))[::STEP]
        rows = (len(frames) + COLUMNS - 1) // COLUMNS
        sheet = Image.new("RGBA", (COLUMNS * FRAME, rows * FRAME), (0, 0, 0, 0))
        for i, path in enumerate(frames):
            im = Image.open(path).convert("RGBA").resize((FRAME, FRAME), Image.LANCZOS)
            sheet.paste(im, ((i % COLUMNS) * FRAME, (i // COLUMNS) * FRAME))
        sheet.save(os.path.join(out, "vibintoast.png"), optimize=True)
    with open(os.path.join(out, "vibintoast.rcss"), "w", newline="\n") as f:
        f.write("/* Generated by tools/gen_jfg_launcher_sheet.py: the frames of the VibinToast icon on the launcher's About page. */\n")
        f.write("@spritesheet vibintoast\n{\n    src: /jfg_vibintoast;\n")
        for i in range(len(frames)):
            f.write(f"    toast{i}: {(i % COLUMNS) * FRAME}px {(i // COLUMNS) * FRAME}px {FRAME}px {FRAME}px;\n")
        f.write("}\n")
    print(f"{len(frames)} frames")

if __name__ == "__main__":
    main()
