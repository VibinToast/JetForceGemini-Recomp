#!/usr/bin/env python3
"""Generate the symbol files in JFGRecompSyms from the matching decomp's ELF.

    gen_reference_syms.py <rom> <decomp jfg.us.elf> <out dir> [--allow-list <file> [--public-baseline <file>]]

With --allow-list it writes the trimmed files that are published (the decomp is private until it's released):
function names already public (--public-baseline: the port's first published function file) stay, names on the
allow-list stay, and every other name becomes the placeholder the decomp gives an unnamed symbol at that address
(func_80045F00_46B00, D_overlay_3_000000A8_1ED5588). Addresses, sizes and relocations don't change. See "Symbol
names: what is public and what stays private" in Recomp-Docs/MOD_SUPPORT.md.

Writes, in N64Recomp's reference-symbol format (the same layout as Zelda64RecompSyms / Snap64RecompSyms):
  <out>/jfg.us.syms.toml      every function by section: `.main` and `.overlay_1`..`.overlay_155`, overlays at the
                              private link addresses of tools/prepare_overlays.py (from 0x82000000), plus each
                              overlay's self-relocations. The port's N64Recomp run reads this file.
  <out>/jfg.us.datasyms.toml  the game's variables and labels by section, for mods (`data_reference_syms_files`).
                              Each overlay's data and bss go in its own function section, as in Zelda64RecompSyms;
                              main's bss gets a `.main_bss` section with no ROM address.
Names, addresses and sizes only: no code or data of the game. Run it in WSL (it uses readelf, like
prepare_overlays.py). The ROM is read only for the overlay linker tables.
"""
import argparse, collections, os, re, subprocess, sys, tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import prepare_overlays as po  # noqa: E402

MAIN_ROM, MAIN_VRAM = po.MAIN_ROM, po.MAIN_VRAM
HEADER = ("# Symbols for Jet Force Gemini (US): main segment + 155 overlay sections (functions and self-relocations).\n"
          "# Generated by tools/gen_reference_syms.py from the matching decomp ELF and the ROM linker tables. Do not edit by hand.\n"
          "# Overlay sections are linked at private addresses from 0x82000000 (see tools/prepare_overlays.py).\n")
DATA_HEADER = ("# Data symbols for Jet Force Gemini (US), for mods (N64Recomp's RecompModTool, data_reference_syms_files).\n"
               "# Generated by tools/gen_reference_syms.py from the matching decomp ELF. Do not edit by hand.\n"
               "# Overlay sections match jfg.us.syms.toml (private link addresses from 0x82000000).\n")


def readelf(args, elf):
    return subprocess.run(["readelf"] + args + [elf], capture_output=True, text=True, check=True).stdout.splitlines()


def sections(elf):
    """index -> (name, addr, size)"""
    out = {}
    for line in readelf(["-SW"], elf):
        p = line.replace("[", " ").replace("]", " ").split()
        if len(p) > 6 and p[0].isdigit():
            out[int(p[0])] = (p[1], int(p[3], 16), int(p[5], 16))
    return out


def symbols(elf):
    """(index in symtab, value, size, type, bind, shndx, name)"""
    out = []
    for line in readelf(["-sW"], elf):
        p = line.split()
        if len(p) == 8 and p[0].endswith(":") and p[0][:-1].isdigit():
            out.append((int(p[0][:-1]), int(p[1], 16), int(p[2], 0), p[3], p[4], p[6], p[7]))  # size: decimal or 0x
    return out


def plain(name):
    """A name a mod can use: no compiler-local labels, function-local statics ("firstTime:1") or NON_MATCHING shadow
    symbols."""
    return not (name.startswith((".", "$", "L_", "jlabel")) or "." in name or ":" in name
                or name.startswith("__") and name.endswith("_s"))


# src/hasm/gen_anim_data.s: one recompiled function with 16 entry points (tools/merge_gen_anim_data.py). Only labels
# with a sized symbol are listed inside it (they're `ignored` in jfg.us.toml); the rest stay out of the file.
GEN_ANIM_DATA = (0x80073E80, 0x80074E50)


def main_functions(secs, syms, main_idx):
    _, start, size = secs[main_idx]
    funcs = [s for s in syms if s[3] == "FUNC" and s[5] == str(main_idx) and plain(s[6])]
    lo, hi = GEN_ANIM_DATA
    funcs = [s for s in funcs if not (lo < s[1] < hi and s[2] == 0)]
    # One name per address: a global, sized symbol beats a weak alias (`__sinf` over `sinf`); then symbol-table order.
    best = {}
    for s in funcs:
        key = (s[4] != "WEAK", s[2] > 0, -s[0])
        if s[1] not in best or key > best[s[1]][0]:
            best[s[1]] = (key, s)
    funcs = sorted((v[1] for v in best.values()), key=lambda s: s[0])
    addrs = sorted({s[1] for s in funcs} | {start + size})
    nxt = {a: addrs[i + 1] for i, a in enumerate(addrs[:-1])}
    counts = collections.Counter(s[6] for s in funcs)
    out = []
    for idx, value, sz, _, _, _, name in funcs:  # symbol-table order
        if value == lo:
            size_ = hi - lo  # the whole blob
        elif lo < value < hi:
            size_ = sz
        else:
            size_ = sz or nxt[value] - value  # the ELF size; asm functions have none: up to the next function
        if counts[name] > 1:
            name = "%s_%08X" % (name, value - MAIN_VRAM + MAIN_ROM)
        out.append((name, value, size_))
    # The boot entry point (an ABS symbol in the ELF), under the name N64Recomp's runtime expects.
    entry = next((s for s in syms if s[6] == "entrypoint" and s[3] == "FUNC"), None)
    if entry:
        out.append(("recomp_entrypoint", entry[1], entry[2]))
    return out


def overlay_sections(rom, elf):
    """The overlay part of the function file, exactly as prepare_overlays.py writes it."""
    with tempfile.TemporaryDirectory() as tmp:
        po.main(rom, elf, os.path.join(tmp, "rom.z64"), os.path.join(tmp, "ovl.toml"), os.path.join(tmp, "dyn.json"))
        return open(os.path.join(tmp, "ovl.toml")).read()


def data_symbols(rom_path, secs, syms):
    lk = po.Linker(open(rom_path, "rb").read())
    by_name = {v[0]: k for k, v in secs.items()}
    main_idx, bss_idx = by_name[".main"], by_name.get(".main_bss")
    ovl_idx = {}
    for k, (name, _, _) in secs.items():
        m = re.fullmatch(r"\.overlay_(\d+)(_bss)?", name)
        if m:
            ovl_idx[k] = (int(m.group(1)), bool(m.group(2)))
    main_data, main_bss, ovl = [], [], collections.defaultdict(list)
    for _, value, _, typ, bind, shndx, name in syms:
        if typ == "FUNC" and shndx != "ABS" or typ in ("FILE", "SECTION") or not plain(name):
            continue
        if shndx == str(main_idx):
            main_data.append((name, value))
        elif bss_idx is not None and shndx == str(bss_idx):
            main_bss.append((name, value))
        elif shndx.isdigit() and int(shndx) in ovl_idx:
            num, is_bss = ovl_idx[int(shndx)]
            ov = lk.overlays[num]
            ovl[num].append((name, ov.link + (ov.text + ov.data if is_bss else 0) + value))
        elif shndx == "ABS":
            m = re.fullmatch(r"(?:D|jtbl)_overlay_(\d+)_([0-9A-F]{8})(?:_[0-9A-F]+)?", name)
            if m and int(m.group(1)) in lk.overlays:
                ov = lk.overlays[int(m.group(1))]
                # Some extracted labels carry an absolute address instead of an overlay offset
                # (D_overlay_61_800036B0): outside the overlay, and RecompModTool rejects the >32-bit sum.
                if int(m.group(2), 16) < ov.text + ov.data + ov.bss:
                    ovl[int(m.group(1))].append((name, ov.link + int(m.group(2), 16)))
    out = [DATA_HEADER]

    def section(name, rom, vram, size, items):
        if not items:
            return
        out.append("[[section]]\nname = \"%s\"\n%svram = 0x%08X\nsize = 0x%X\n\nsymbols = [" %
                   (name, "" if rom is None else "rom = 0x%08X\n" % rom, vram, size))
        seen = set()
        for n, v in sorted(items, key=lambda x: (x[1], x[0])):
            if n in seen:
                continue
            seen.add(n)
            out.append("    { name = \"%s\", vram = 0x%08X }," % (n, v))
        out.append("]\n")

    _, mstart, msize = secs[main_idx]
    section(".main", MAIN_ROM, mstart, msize, main_data)
    if bss_idx is not None:
        _, bstart, bsize = secs[bss_idx]
        section(".main_bss", None, bstart, bsize, main_bss)
    for num, ov in sorted(lk.overlays.items()):
        if ov.text:
            section(".overlay_%d" % num, ov.rom, ov.link, ov.text + ov.data, ovl.get(num, []))
    return "\n".join(out), sum(len(set(n for n, _ in v)) for v in [main_data, main_bss] + list(ovl.values()))


ENTRY = re.compile(r'^(\s*\{ name = ")([^"]+)(", vram = 0x([0-9A-F]+).*)$')
# A name the decomp hasn't given yet. Published as it is, even when it doesn't match its address (D_800A7980 at
# 0x800A6FC0): it reveals nothing.
UNNAMED = re.compile(r"(?:func|D|jtbl)_(?:overlay_\d+_)?[0-9A-F]{8}(?:_[0-9A-F]+)?")


def section_entries(text):
    """Yield (line index, section name, section rom or None, section vram, section size, regex match or None)."""
    sec = rom = vram = size = None
    for i, line in enumerate(text.split("\n")):
        if line == "[[section]]":
            sec = rom = vram = size = None
        m = re.fullmatch(r'name = "(\.[^"]+)"', line)
        if m:
            sec = m.group(1)
        for key in ("rom", "vram", "size"):
            m = re.fullmatch(key + r" = 0x([0-9A-Fa-f]+)", line)
            if m:
                if key == "rom":
                    rom = int(m.group(1), 16)
                elif key == "vram":
                    vram = int(m.group(1), 16)
                else:
                    size = int(m.group(1), 16)
        yield i, line, sec, rom, vram, size, ENTRY.match(line)


def placeholder(prefix, sec, rom, vram, size, addr):
    """The name the decomp gives an unnamed symbol at addr: func_80044FAC_45BAC, D_overlay_16_00004440_1F22458, and an
    overlay's bss without the ROM part (D_overlay_3_0001A120)."""
    if sec in (".main", ".main_bss"):
        return "%s_%08X_%X" % (prefix, addr, addr - MAIN_VRAM + MAIN_ROM)
    num, off = int(sec.split("_")[1]), addr - vram
    if rom is None or off >= size:
        return "%s_overlay_%d_%08X" % (prefix, num, off)
    return "%s_overlay_%d_%08X_%X" % (prefix, num, off, rom + off)


def trim(text, prefix, allow, public):
    """The published ("trimmed") file. Per symbol: a name on the allow-list stays; else the name already published for
    that address (public, {(section, vram): name}); else a name the decomp hasn't given yet stays; else the placeholder.
    Addresses, sizes and relocations are unchanged. Names that end up twice in a section are written once."""
    lines, seen, n_hidden = text.split("\n"), set(), 0
    for i, line, sec, rom, vram, size, m in section_entries(text):
        if not m:
            continue
        name, addr = m.group(2), int(m.group(4), 16)
        if name in allow:
            new = name
        elif (sec, addr) in public:
            new = public[(sec, addr)]
        elif UNNAMED.fullmatch(name):
            new = name
        else:
            new = placeholder(prefix, sec, rom, vram, size, addr)
        n_hidden += new != name
        if (sec, new) in seen:
            lines[i] = None
            continue
        seen.add((sec, new))
        lines[i] = m.group(1) + new + m.group(3)
    return "\n".join(l for l in lines if l is not None), n_hidden


def public_names(path):
    """{(section, vram): name} from an already published function file (the baseline)."""
    text = open(path, encoding="utf-8").read()
    return {(sec, int(m.group(4), 16)): m.group(2) for _, _, sec, _, _, _, m in section_entries(text) if m}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("rom")
    ap.add_argument("elf")
    ap.add_argument("out_dir")
    ap.add_argument("--allow-list", help="write the trimmed (public) files: only these names (one per line, # comments) "
                    "are kept, plus the baseline's; every other name becomes its placeholder")
    ap.add_argument("--public-baseline", help="a function file already published: its names stay as they are")
    a = ap.parse_args()
    secs, syms = sections(a.elf), symbols(a.elf)
    main_idx = next(k for k, v in secs.items() if v[0] == ".main")
    _, mstart, msize = secs[main_idx]
    funcs = main_functions(secs, syms, main_idx)
    text = [HEADER, "[[section]]\nname = \".main\"\nrom = 0x%08X\nvram = 0x%08X\nsize = 0x%X\n\nfunctions = [" %
            (MAIN_ROM, mstart, msize)]
    text += ["    { name = \"%s\", vram = 0x%08X, size = 0x%X }," % f for f in funcs]
    text.append("]\n")
    func_text = "\n".join(text) + "\n" + overlay_sections(a.rom, a.elf)
    data, n_data = data_symbols(a.rom, secs, syms)
    if a.allow_list:
        allow = {l.split("#")[0].strip() for l in open(a.allow_list, encoding="utf-8")} - {""}
        public = public_names(a.public_baseline) if a.public_baseline else {}
        func_text, f_hidden = trim(func_text, "func", allow, public)
        data, d_hidden = trim(data, "D", allow, {})
        print("trimmed: %d function and %d data names replaced by placeholders" % (f_hidden, d_hidden))
    os.makedirs(a.out_dir, exist_ok=True)
    open(os.path.join(a.out_dir, "jfg.us.syms.toml"), "w", newline="\n").write(func_text)
    open(os.path.join(a.out_dir, "jfg.us.datasyms.toml"), "w", newline="\n").write(data)
    print("main functions: %d; data symbols: %d -> %s" % (len(funcs), n_data, a.out_dir))


if __name__ == "__main__":
    main()
